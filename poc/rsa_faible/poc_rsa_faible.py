def attaque(wrapped_bytes):
    c = int.from_bytes(wrapped_bytes, "big")
    
    # Calcul exact de la racine cubique entière (évite les pertes de précision des floats)
    def integer_cbrt(n):
        if n == 0:
            return 0
        x = 1 << ((n.bit_length() + 2) // 3)
        while True:
            y = (2 * x + n // (x * x)) // 3
            if y >= x:
                return x
            x = y

    m = integer_cbrt(c)
    file_key = m.to_bytes(32, "big")
    return file_key

